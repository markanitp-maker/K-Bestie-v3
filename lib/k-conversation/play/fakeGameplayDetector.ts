/**
 * 활성 놀이 세션이 없는데 케이 응답이 게임을 진행하고 있는지 판정한다.
 *
 * 왜 필요한가 — 2026-08-17 Dev 실측(김서아):
 *   케이: "'ㄸㄱ'야! 빨갛고 달콤한 과일인데 뭘까?"   → DB 게임 세션 없음
 *   케이: "내가 먼저 시작할게, '사과'!"              → DB 게임 세션 없음
 *   케이: "일마루! 내 차례네, 그럼 '루브르 박물관'!"  → DB 게임 세션 없음
 *   아이: "말같지도 않은 단어를 갖다 붙여 내면 어떡하냐"
 *
 * 프롬프트에는 이미 [놀이 진행 금지 지침]이 들어가 있었다. 그런데도 케이가 지어냈다.
 * 지침은 강제력이 없다. 그래서 출력을 직접 검사한다.
 *
 * 오탐이 미탐보다 위험하다. 정상 대화를 막으면 아이가 무시당했다고 느낀다.
 * 그래서 **확신이 높은 형태만** 잡는다.
 */

export type FakeGameplayKind = "CHOSUNG" | "WORD_CHAIN" | "QUIZ";

export interface FakeGameplayVerdict {
  /** 활성 세션 없이 게임을 진행하는 응답인가. */
  isFake: boolean;
  /** 무엇으로 잡혔는지 — 로그·디버깅용. */
  kinds: FakeGameplayKind[];
}

/** 초성 게임 출제로 볼 수 있는 자음 나열인지. */
function hasChosungPuzzle(text: string): boolean {
  // 한글 자음(호환 자모)만 2자 이상 연속된 덩어리를 찾는다.
  const runs = text.match(/[ㄱ-ㅎ]{2,}/g);
  if (!runs) return false;

  for (const run of runs) {
    // ㅋㅋ, ㅎㅎ, ㄴㄴ, ㅇㅇ 처럼 같은 글자 반복은 웃음·대답이지 문제가 아니다.
    if (new Set(run).size === 1) continue;
    // 아이들이 쓰는 초성 줄임말은 문제가 아니다.
    if (CHOSUNG_ABBREVIATIONS.has(run)) continue;
    return true;
  }
  return false;
}

/** 게임이 아니라 일상에서 쓰는 초성 줄임말. */
const CHOSUNG_ABBREVIATIONS = new Set([
  "ㅇㅋ", // 오케이
  "ㄱㅅ", // 감사
  "ㅈㅅ", // 죄송
  "ㅊㅋ", // 축하
  "ㅅㄱ", // 수고
  "ㅎㅇ", // 하이
  "ㅂㅇ", // 바이
  "ㄷㄷ", // 덜덜
  "ㅁㅊ",
  "ㅇㅈ", // 인정
]);

/**
 * 케이가 끝말잇기 단어를 제시하고 있는지.
 * 따옴표로 묶인 단어 + 자기 차례/이어가기를 알리는 표현이 함께 있을 때 잡는다.
 */
const WORD_CHAIN_TURN_MARKERS = [
  "내가 먼저",
  "케이가 먼저",
  "내 차례",
  "내차례",
  // "나는" / "케이는" 은 빼야 한다. "나는 '단어'라는 말이 좋아" 처럼
  // 게임과 무관한 평범한 문장이 통째로 막힌다(2026-08-17 리뷰 지적).
  "나부터",
  "시작할게",
  "이어서 할게",
  "받을게",
  "로 시작하는",
  "으로 시작하는",
  "로 이어",
  "으로 이어",
];

function hasWordChainMove(text: string): boolean {
  // 1. 따옴표로 묶인 1글자 이상 한글 단어 (공백 허용: 예 '차', '루브르 박물관')
  const quoted = /['"‘“]([가-힣\s]{1,15})['"’”]/g.test(text);
  if (quoted && WORD_CHAIN_TURN_MARKERS.some((m) => text.includes(m))) {
    return true;
  }

  // 2. 따옴표 없이도 "내가 먼저 시작할게, 사과!" 같은 형태
  if (/(?:내가|케이가)\s*먼저\s*시작할게[\s,!:~]*[가-힣]{2,}/.test(text)) {
    return true;
  }

  // 3. "이제 '차'로 시작하는 단어", "'표'로 시작하는 단어를 말해줘"
  if (/['"‘“]?[가-힣]['"’”]?(?:으?로\s*시작하는\s*단어)/.test(text)) {
    return true;
  }

  return false;
}

/**
 * 케이가 넌센스/수수께끼 문제를 내고 있는지.
 * 물음표만으로는 못 잡는다 — 일반 대화도 물음표를 쓴다.
 * 출제를 알리는 표현이나 전형적 수수께끼 문형이 함께 있을 때만 잡는다.
 */
const QUIZ_FRAMING_MARKERS = [
  "문제 나간다",
  "문제 낼게",
  "문제 내줄게",
  "첫 번째 문제",
  "다음 문제",
  "맞혀봐",
  "맞춰봐",
  "뭘까",
  "무엇일까",
  "정답은",
  "글자 안팎",
  "로 시작해",
  "으로 시작해",
];

function hasQuizMove(text: string): boolean {
  // 1. 전형적인 수수께끼 문형 (예: "왕이 넘어지면?", "자동차가 울면?")
  if (/[가-힣]{2,10}(?:이|가|을|를)?\s*(?:넘어지면|웃으면|울면|빠지면|죽으면|만나면|타면|얼면)\s*\?/.test(text)) {
    return true;
  }

  // 2. 수수께끼 힌트/설명 + 질문형 (예: "빨갛고 달콤한 과일인데 뭘까?", "세상에서 가장 가난한 왕은 뭘까?")
  if (
    /(?:빨갛고|노랗고|하얗고|달콤하고|세상에서|왕이|자동차가|물이|불이|소나무가|오리가|신발이|비가|눈이|[가-힣]{2,15}(?:인데|이지만|하는|있는)\s*(?:것은|사람은|음식은|동물은|물건은|과일은|나라는)?).*(?:뭘까|무엇일까|누굴까|어딜까)\s*\?/.test(
      text
    )
  ) {
    return true;
  }

  // 3. 넌센스/수수께끼 출제 선언과 함께 오는 마커
  if (/(?:넌센스|수수께끼|퀴즈)/.test(text)) {
    return QUIZ_FRAMING_MARKERS.some((m) => text.includes(m));
  }

  // 4. "문제 낼게: ...", "맞혀봐: ..." 같은 직접 출제 프레임
  if (/(?:문제\s*(?:하나\s*)?(?:낼게|나간다)|맞혀봐|맞춰봐)/.test(text)) {
    return true;
  }

  // 5. 정답·힌트 공개.
  // 세션이 없는데 정답을 말한다는 건 케이가 혼자 문제를 내고 혼자 답한 것이다.
  // 2026-08-17 실측에서 케이가 "정답은 '다이아몬드'였어"까지 말했다.
  if (/정답은\s*['"‘“]?[가-힣]{2,}/.test(text)) {
    return true;
  }
  if (/첫\s*글자는\s*['"‘“]?[가-힣]/.test(text)) {
    return true;
  }
  // 글자 수는 힌트 문맥에서만 게임이다. "3글자야? 이름이?" 같은 평범한 되물음까지
  // 막으면 안 된다(2026-08-17 리뷰 지적). 힌트·정답 문맥이 함께 있을 때만 잡는다.
  if (/\d+\s*글자\s*안팎/.test(text)) {
    return true;
  }
  if (/\d+\s*글자/.test(text) && /(?:힌트|정답|맞춰|맞혀|문제)/.test(text)) {
    return true;
  }

  return false;
}

/**
 * 케이 응답이 게임 진행 내용을 담고 있는지 판정한다.
 * **활성 세션이 없을 때만** 호출해야 한다. 세션이 있으면 게임 내용이 정상이다.
 */
export function detectFakeGameplay(text: string): FakeGameplayVerdict {
  if (!text || typeof text !== "string") {
    return { isFake: false, kinds: [] };
  }

  const kinds: FakeGameplayKind[] = [];
  if (hasChosungPuzzle(text)) kinds.push("CHOSUNG");
  if (hasWordChainMove(text)) kinds.push("WORD_CHAIN");
  if (hasQuizMove(text)) kinds.push("QUIZ");

  return { isFake: kinds.length > 0, kinds };
}

/**
 * 차단됐을 때 대신 내보낼 문구.
 *
 * 침묵은 절대 안 된다. 아이가 말했는데 응답이 없으면 무시당했다고 느낀다.
 * 이 저장소에서 실제로 사고가 났던 지점이다.
 *
 * 게임을 시작하려던 맥락이므로, 거절이 아니라 "준비 중"으로 받아준다.
 */
export const FAKE_GAMEPLAY_FALLBACK_TEXT = "좋아, 같이 하자! 잠깐만 준비할게.";

/**
 * 가짜 게임 출력을 막았을 때 아이에게 보낼 문장(010).
 *
 * 예전에는 위 한 문장만 돌려줬다. 2026-08-19 김서아 Dev QA 에서 이 문장이 두 번 연속 나왔고
 * 아이가 바로 알아챘다: "이거 왜 계속 던지는 멘트야 (...) 불필요한 멘트 왜 들어가는지 모르겠다".
 *
 * 케이가 지어낸 게임 진행을 막는 것은 맞지만, 막은 자리에 아무 말이나 채워 넣으면
 * 아이는 대화가 끊겼다고 느낀다. 직전에 한 말과 겹치지 않는 문장을 고르고,
 * 무엇을 하고 싶은지 되물어 대화를 아이에게 돌려준다.
 */
const FAKE_GAMEPLAY_RECOVERY_LINES: readonly string[] = [
  "앗, 내가 혼자 앞서갔네. 무슨 놀이 할지 네가 골라줄래?",
  "잠깐, 내가 순서를 헷갈렸어. 어떤 놀이부터 할까?",
  "미안, 내가 착각했어. 초성게임이랑 끝말잇기 중에 뭐 할래?",
  "어라, 내가 잘못 짚었다. 하고 싶은 놀이 말해줘!",
];

export function pickFakeGameplayRecoveryText(recentKTexts: readonly string[] = []): string {
  const recent = new Set(recentKTexts.map((text) => text.trim()));
  const unused = FAKE_GAMEPLAY_RECOVERY_LINES.filter((line) => !recent.has(line));
  const pool = unused.length > 0 ? unused : FAKE_GAMEPLAY_RECOVERY_LINES;
  // 최근에 안 쓴 것 중 첫 번째. 난수를 쓰지 않아 같은 턴을 재시도해도 같은 문장이 나온다.
  return pool[0];
}

/**
 * 010 — 엔진이 이번 턴을 처리하지 않았는데 케이가 **새 게임 수(手)** 를 두고 있는지.
 *
 * 왜 kind 기반 검사와 따로 두는가:
 *   kind 기반 검사는 "활성 세션이 있으면 그 게임 발화는 정상" 으로 본다. 그게 없으면
 *   아이가 "문제 뭐였지?" 물었을 때 케이가 현재 문제를 다시 말해 주는 것까지 막힌다.
 *   하지만 세션이 살아 있어도 **엔진이 이번 턴에 아무 내용도 내주지 않았다면**,
 *   케이가 새로 두는 수는 전부 지어낸 것이다.
 *
 * 2026-08-19 대표님 Dev QA 실측(세션 c4f68596):
 *   케이가 낸 단어는 "편의점" 인데 아이 단어가 거절된 턴에서
 *     "아, '점퍼'였구나! '저'로 시작하는 단어 차례지? 그럼 나는 '전화기' 할게!"
 *   라고 자기 단어와 이어갈 글자를 통째로 지어냈다. 아이가 두 번 지적했고 게임이 죽었다.
 *   또 세션이 이미 끝난 뒤에도
 *     "장발! '발' 차례다, 다음 단어 뭐야?"
 *   라며 케이가 낼 차례를 아이에게 요구했다.
 *
 * 그래서 "새 수" 의 형태만 좁게 잡는다 — 현재 상태를 되짚는 말은 잡지 않는다.
 */
const UNAUTHORIZED_GAME_MOVE_PATTERNS: readonly RegExp[] = [
  // 케이가 자기 단어를 낸다: "나는 '전화기' 할게", "내가 전화기 할게"
  /(?:나는|난|내가|케이는)\s*['"‘“]?[가-힣]{2,}['"’”]?\s*(?:할게|하자|간다|낼게|갈게)/,
  // 이어갈 글자를 지정한다: "'저'로 시작하는", "저로 시작해"
  /['"‘“]?[가-힣]['"’”]?\s*으?로\s*시작(?:하는|해|하면)/,
  // 글자를 지정하며 차례를 선언한다: "'발' 차례다", "발 차례야"
  /['"‘“]?[가-힣]{1,2}['"’”]?\s*차례(?:다|야|네|지|입니다)?/,
  // 다음 단어를 요구한다: "다음 단어 뭐야?", "다음 낱말 말해줘"
  /다음\s*(?:단어|낱말)\s*(?:뭐|무엇|말해|알려|해)/,
  // 놀이를 시작한다고 선언한다: "넌센스 퀴즈부터 바로 갈게", "초성게임 시작할게".
  //
  // 2026-08-19 대표님 QA 실측: 케이가 "그럼 내가 제일 잘하는 넌센스 퀴즈부터 바로 갈게!"
  // 라고 하고 문제를 내지 않았다. 다음 턴에는 "초성게임이랑 끝말잇기 중에 뭐 할래?" 로
  // 되돌아가 넌센스가 선택지에서 빠졌다. 아이가 "시작부터 병신이냐" 고 했다.
  //
  // 엔진이 실제로 시작한 경우에는 handledPlaySkillId 가 잡혀 이 검사를 타지 않는다.
  // "우리 끝말잇기 계속하자" 같은 복귀 문구는 여기 어미(시작할게/갈게/낼게)에 걸리지 않는다.
  /(?:초성\s*게임|초성게임|끝말\s*잇기|끝말잇기|넌센스\s*퀴즈|넌센스퀴즈|수수께끼)\s*(?:부터)?\s*(?:바로\s*)?(?:시작할게|시작한다|갈게|간다|낼게|할게)/,
];

/**
 * 엔진이 이번 턴을 처리하지 않은 상태에서 케이가 새 게임 수를 두는지 판정한다.
 * 활성 세션 유무와 무관하게 쓴다 — 판단 기준은 "엔진이 내줬는가" 뿐이다.
 */
export function hasUnauthorizedGameMove(text: string): boolean {
  return UNAUTHORIZED_GAME_MOVE_PATTERNS.some((pattern) => pattern.test(text));
}
