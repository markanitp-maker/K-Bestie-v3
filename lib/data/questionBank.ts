import type { Axis, Pole } from "./mbtiTypes";

/** 문항의 한 선택지. pole은 해당 축의 두 극 중 하나로 배점된다. */
export interface QuestionChoice {
  /** 화면 표시 및 답변 저장용 식별자. */
  id: "A" | "B";
  /** 아동이 읽는 선택지 문구(짧은 문장 1개). */
  text: string;
  /** 이 선택지를 고르면 배점되는 극. */
  pole: Pole;
}

export interface Question {
  /** 문항 고유 ID. 축-순번 형태(예: "EI-1"). */
  id: string;
  /** 이 문항이 속한 진단 축. */
  axis: Axis;
  /**
   * 실제 문항 화면 노출 순서(1~16). 같은 축 문항이 연속으로 몰리지 않도록
   * EI → SN → TF → JP 순으로 라운드 로빈 배치했다(아이가 축 구조를 눈치채지
   * 않도록 하는 목적, 최종 셔플 여부는 UI 구현 단계 재량).
   */
  order: number;
  /** 아동에게 보이는 상황 설명 문구(질문). */
  prompt: string;
  /** 두 선택지. 각각 해당 축의 서로 다른 극에 배점된다. */
  choices: readonly [QuestionChoice, QuestionChoice];
  /**
   * Imagen 4 이미지 생성용 프롬프트 초안(한국어). 실제 생성 호출은
   * SPEC.md §0 STOP 조건에 따라 승인 후 진행하며, 여기서는 프롬프트 텍스트만
   * 준비한다.
   */
  imagePrompt: string;
}

