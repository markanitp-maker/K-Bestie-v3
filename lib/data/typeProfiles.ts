/** 모든 16유형에 프로필이 정확히 존재하는지 검사하는 헬퍼(테스트/런타임 가드용). */
export function assertTypeProfilesShape(
  profiles: Readonly<Record<MbtiType, MbtiTypeProfile>>,
): void {
  for (const type of ALL_MBTI_TYPES) {
    const profile = profiles[type];
    if (!profile) {
      throw new Error(`${type} 유형 프로필이 없습니다.`);
    }
    if (profile.type !== type) {
      throw new Error(`${type} 프로필의 type 필드가 일치하지 않습니다.`);
    }
    if (profile.strengths.length < 2 || profile.strengths.length > 4) {
      throw new Error(`${type} strengths는 2~4개여야 합니다.`);
    }
    if (profile.parentTips.length < 2 || profile.parentTips.length > 4) {
      throw new Error(`${type} parentTips는 2~4개여야 합니다.`);
    }
  }
}
